#!/usr/bin/env python3
# Emit an embeddable C byte array for a SPIR-V module so a host-side probe/runtime can
# build a VkShaderModule / VkPipeline without shipping an external asset file. Reproducible:
# records the source path, the compiler-used note and the module SHA-256 in the comment.
#
#   python3 tools/emit-spirv-header.py <in.spv> <out.h> <symbolName>
import hashlib
import sys
from pathlib import Path


def main() -> int:
    spv = Path(sys.argv[1])
    out = Path(sys.argv[2])
    symbol = sys.argv[3]
    data = spv.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if len(data) % 4:
        raise SystemExit(f"{spv} is not a multiple of 4 bytes (not SPIR-V word aligned)")
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    lines = [
        "// Generated by tools/emit-spirv-header.py",
        f"// Source SPIR-V: {spv}  sha256={digest}",
        f"// {len(data)} bytes = {len(words)} SPIR-V words (uint32). Regenerate with pinned glslc.",
        "// This fork's VkShaderModuleCreateInfo::pCode is a const uint32_t*, so the",
        "// payload is stored as 32-bit words (aligned); codeSize stays in BYTES.",
        "#include <cstdint>",
        f"static const std::uint32_t {symbol}[] = {{",
    ]
    row: list[str] = []
    for word in words:
        row.append(f"0x{word:08x}u")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(data)} bytes = {len(words)} words, sha256={digest})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
